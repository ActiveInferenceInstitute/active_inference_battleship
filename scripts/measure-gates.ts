import { mkdir, writeFile } from "node:fs/promises";
import { release } from "node:os";
import { dirname, join, resolve } from "node:path";
import { externalEnvironment, projectRoot } from "./paths";

type Sample = { command: string; milliseconds: number; status: number };
const baseline = (await Bun.file(join(projectRoot, "scripts/gate-baseline.json")).json()) as {
  source: string;
  date: string;
  environment: string;
  samples: Record<string, Sample>;
  notes: string[];
};
const arms = ["lint", "types", "test:fast", "test:full", "docs", "gnn", "build", "fast", "all"];
const args = process.argv.slice(2);
if (args.length && (args[0] !== "--output" || args.length !== 2))
  throw new Error("Usage: bun run gate:measure [--output FILE]");
const documentPath = resolve(projectRoot, args[1] ?? "docs/_generated/gate-timings.md");
const env = externalEnvironment();
const output = join(projectRoot, ".cache/gate-measurements");
await mkdir(output, { recursive: true });
const rows: string[] = [];
let failed = false;
for (const arm of arms) {
  const argv = ["bun", "run", "gate", arm];
  const start = performance.now();
  const child = Bun.spawn(argv, {
    cwd: projectRoot,
    env,
    stdin: "ignore",
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr, status] = await Promise.all([
    new Response(child.stdout).text(),
    new Response(child.stderr).text(),
    child.exited,
  ]);
  const milliseconds = Math.round(performance.now() - start);
  await writeFile(join(output, `${arm.replaceAll(":", "-")}.log`), stdout + stderr);
  const tests = /Ran (\d+) tests across (\d+) files/.exec(stdout + stderr);
  const before = baseline.samples[arm];
  rows.push(
    `| \`${arm}\` | ${before ? (before.milliseconds / 1000).toFixed(3) : "— (new arm)"} | ${(milliseconds / 1000).toFixed(3)} | ${status === 0 ? "PASS" : `FAIL (${status})`} | ${tests ? `${tests[1]} / ${tests[2]}` : "—"} |`,
  );
  console.log(`${argv.join(" ")}: ${milliseconds} ms, exit ${status}`);
  if (status !== 0) {
    console.error(stderr);
    failed = true;
  }
}
const document = `# Local gate measurements

<!-- Generated by bun run gate:measure; do not hand-edit. -->

Measured ${new Date().toISOString()} on ${process.platform} ${release()} ${process.arch}, Bun ${Bun.version} (Node-compat ${process.versions.node}, not the installed Node executable).
One sequential wall-time sample per arm; setup/install excluded. Logs: \`.cache/gate-measurements/\` (local-only).

Baseline: ${baseline.source}, ${baseline.date}. ${baseline.environment}.
Baseline commands and original observations: [gate-baseline.json](../../scripts/gate-baseline.json).
After commands: \`bun run gate <arm>\`; actual leaves live in [scripts/run.ts](../../scripts/run.ts).

| Arm | Before (s) | After (s) | After result | Tests / files |
| --- | ---: | ---: | --- | ---: |
${rows.join("\n")}

The old \`check\` is compared with \`all\`, not the new reduced-scope default \`fast\`.
The latter deliberately excludes the two subprocess integration suites and coverage; it is not equivalent full acceptance.
The new full plan also checks docs/links. One sample does not establish a general speedup.

${baseline.notes.map((note) => `- ${note}`).join("\n")}

Refresh from the repository root with \`bun run gate:measure\` using the documented interpreter prerequisites in [RUN_GUIDE](../RUN_GUIDE.md).
Bun counts describe only its selected suites, never browser, Python bridge or whole-upstream coverage.
`;
await mkdir(dirname(documentPath), { recursive: true });
await writeFile(documentPath, document);
if (failed) process.exit(1);
